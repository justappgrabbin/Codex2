// Optional Playwright acceptance. Use a fresh test data directory, not private work.
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.SYNTHIA_PLAYWRIGHT_MODULE ?? 'playwright');
const origin = process.env.SYNTHIA_TEST_ORIGIN ?? 'http://127.0.0.1:8765';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const checks = [];
try {
  await page.goto(origin);
  await page.getByRole('button', { name: 'Computer', exact: true }).click();
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  const fixture = new URL('../tests/fixtures/standalone-counter/', import.meta.url);
  await page.getByLabel('Import project files', { exact: true }).setInputFiles(['package.json', 'build.mjs', 'counter.test.mjs', 'index.html'].map(path => fileURLToPath(new URL(path, fixture))));
  await page.getByRole('button', { name: 'Plan work', exact: true }).first().waitFor();
  checks.push('Actual desktop import');
  await page.getByRole('button', { name: 'Research', exact: true }).click();
  await page.getByLabel('Evidence query').fill('standalone counter');
  await page.getByRole('button', { name: 'Search sources', exact: true }).click();
  checks.push('Resident evidence search');
  await page.getByRole('button', { name: 'Capabilities', exact: true }).click();
  await page.getByText('UNVERIFIED', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Planner', exact: true }).click();
  await page.getByLabel('Project', { exact: true }).selectOption({ index: 1 });
  const goal = `Verify standalone counter ${Date.now()}`;
  await page.getByLabel('Goal', { exact: true }).fill(goal);
  await page.getByRole('button', { name: 'Prepare inspectable plan' }).click();
  await page.getByRole('button', { name: 'Approve this plan: one isolated build/test' }).last().click();
  await page.getByRole('button', { name: 'Run authorized work' }).last().click();
  await page.getByRole('heading', { name: 'VERIFIED: ' + goal }).waitFor({ timeout: 90000 });
  checks.push('Explicit approval and real Docker build/test through UI');
  await page.getByRole('button', { name: 'Artifacts', exact: true }).click();
  const link = page.getByRole('link').last();
  const artifactURL = await link.getAttribute('href');
  const artifact = await page.request.get(origin + artifactURL).then(response => response.json());
  assert.equal(artifact.receipt.ok, true);
  assert.equal(artifact.kind, 'verified-source-bundle');
  assert.ok(artifact.files.find(file => file.path === 'index.html'));
  await page.getByRole('button', { name: 'Inspect / preview', exact: true }).last().click();
  const frame = page.frameLocator('iframe[title="Isolated source preview"]');
  await frame.getByText('Isolated origin', { exact: true }).waitFor();
  await frame.getByRole('button', { name: 'Increment', exact: true }).click();
  assert.equal(await frame.locator('#count').textContent(), '1');
  assert.equal(await page.locator('iframe').getAttribute('sandbox'), 'allow-scripts');
  const csp = await frame.locator('meta[http-equiv="Content-Security-Policy"]').getAttribute('content');
  assert.ok(csp.includes("connect-src 'none'"));
  checks.push('Real artifact download, interactive source preview, opaque origin and network-denying CSP');
  if (process.env.SYNTHIA_SCREENSHOT_PATH) await page.screenshot({ path: process.env.SYNTHIA_SCREENSHOT_PATH });
  assert.deepEqual(errors, []);
  const proof = { ok: true, checks, pageErrors: errors, jobId: artifact.receipt.jobId, receiptId: artifact.receipt.id };
  if (process.env.SYNTHIA_BROWSER_PROOF_PATH) await writeFile(process.env.SYNTHIA_BROWSER_PROOF_PATH, JSON.stringify(proof, null, 2));
  console.log(JSON.stringify(proof));
} finally { await browser.close(); }
