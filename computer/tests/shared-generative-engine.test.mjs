import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { ConversationExecution } from '../services/conversation-execution.mjs';
import { ComputerRuntime } from '../ComputerRuntime.mjs';
import { JsonFilePersistence } from '../runtime/json-file-persistence.mjs';
import { GenerativeAssemblyService } from '../services/generative-assembly.mjs';
import { attachGenerativeAssembly } from '../integration/shared-generative-engine.mjs';
import { SynthiaAutomata as LegacyEngine } from '../donors/Back-up-/vendor/pure-synthia-v0.4.0/src/synthia/semantic-mesh/engine/synthia.js';

test('Generative analysis shares the resident Computer engine, preserves custom tools, and persists actual receipts', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'synthia-shared-engine-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const persistence = new JsonFilePersistence(join(directory, 'state.json'));
  const computer = await new ComputerRuntime({ persistence }).boot();
  await computer.automataGateway._boot();
  const resident = computer.automataGateway._synthia;
  const engine = resident.meshRuntime.engine;
  const execution = new ConversationExecution(computer);
  assert.equal(execution.execution.engine, engine, 'execution does not construct another semantic engine');
  const originalMesh = engine.mesh;
  const tools = new Map(engine.mesh.automata);
  const neural = resident.neural;
  const tool = engine.mesh.get('autoling');
  const originalRun = tool.run;
  tool.run = function(...args) { return { ...originalRun.apply(this, args), compatibilitySentinel: 'preserved-custom-run' }; };
  const service = new GenerativeAssemblyService({ gateway: computer.automataGateway, state: computer.state, bus: computer.bus });
  const [a, b] = await Promise.all([service.connected(), service.connected()]);
  assert.equal(a, b);
  assert.equal(a.assembly.engine, engine);
  await assert.rejects(attachGenerativeAssembly(engine, { sourceRoot: '/different-authority' }), /different Generative source authority/);
  assert.equal(a.assembly.mesh, originalMesh);
  assert.equal(resident.neural, neural);
  for (const [id, ref] of tools) assert.equal(engine.mesh.get(id), ref, id);
  const run = tool.run({ operation: 'pipeline', text: 'The player moves toward the goal.' });
  assert.equal(run.compatibilitySentinel, 'preserved-custom-run');
  const conversation = await computer.automataGateway.talk('The player moves toward the goal.');
  assert.equal(conversation.conversation.semantic.linguisticGrounded, true, 'original conversation still executes');
  const turn = await execution.talk('The player moves toward the goal.');
  assert.equal(turn.linguisticGrounded, true, 'full Computer conversation uses the shared engine');
  assert.ok(turn.learningRecord);
  assert.ok(turn.text);
  const neuralOutput = await neural.connectionField.call({ operation: 'observe', address: { gate: 3 }, signal: .5 });
  assert.equal(neuralOutput.gate, 3, 'original neural organ still executes');
  const first = await service.inspect({ text: 'The player moves toward the goal.' });
  assert.equal(first.derivation.output.summary.recognitionStatus, 'executed');
  assert.ok(first.derivation.output.summary.recognizedRelationshipCount > 0);
  assert.equal(first.derivation.output.summary.addressCount, 0, 'no semantic address invented');
  assert.ok(engine.tripleStore.query({ predicate: 'produced' }).length > 0);
  const beforeProbe = a.assembly.toolState.snapshot().sequence;
  const owned = tool.exportState();
  engine.klein.evaluate({ invocations: [{ toolId: 'autoling', input: { operation: 'pipeline', text: 'Another player moves.' } }] });
  assert.equal(a.assembly.toolState.snapshot().sequence, beforeProbe, 'probes do not become observations');
  assert.deepEqual(tool.exportState(), owned, 'probe restores owned tool state');
  assert.throws(() => service.inspect({ text: '' }), /1..50,000/);
  const restarted = await new ComputerRuntime({ persistence }).boot();
  const reopened = new GenerativeAssemblyService({ gateway: restarted.automataGateway, state: restarted.state });
  assert.equal(reopened.history()[0].id, first.id);
  assert.deepEqual(reopened.history()[0].derivation.output, first.derivation.output);
});

test('failed adapter mounting rolls back original tools, maps and context hooks', async () => {
  const engine = new LegacyEngine();
  const originalTools = [...engine.tools];
  const originalMap = new Map(engine.mesh.automata);
  const originalTriples = engine.tripleStore.query({});
  const register = engine.mesh.register;
  engine.mesh.register = function(tool) {
    if (tool.id === 'generative-address-morphology') throw new Error('controlled mount failure');
    return register.call(this, tool);
  };
  await assert.rejects(attachGenerativeAssembly(engine), /controlled mount failure/);
  assert.deepEqual(engine.tools, originalTools);
  assert.deepEqual(engine.mesh.automata, originalMap);
  assert.deepEqual(engine.tripleStore.query({}), originalTriples);
  assert.equal(engine.klein, undefined);
  assert.equal(engine.mesh.connectTransport, undefined);
  for (const tool of originalTools) assert.equal(tool.provideContext, undefined);
  engine.mesh.register = register;
  const retry = await attachGenerativeAssembly(engine);
  assert.equal(retry.assembly.engine, engine);
});
