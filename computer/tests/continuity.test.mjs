function resolverComputer(persistence = new MemoryPersistence()) {
  const bus = new EventBus();
  const computer = { bus, state: new StateStore({ bus, persistence }), capabilityRegistry: new Registry({ kind: 'capability', bus }) };
  computer.contextual = new ContextualCapabilities(computer); return computer;
}
test('context changes retain identity, trust gates, evidence, dependency chains and durable checkpoints', async () => {
  const persistence = new MemoryPersistence(), computer = resolverComputer(persistence);
  await computer.state.restore(); await computer.contextual.boot();
  const resolver = computer.contextual;
  await resolver.register({ id: 'python-tool', source: { repository: 'original', version: 'v1' }, digest: 'abc', environment: ['python'], meaning: { original: 'source-specific module' } });
  assert.equal(resolver.get('python-tool').applicability, 'DEFERRED');
  computer.bus.emit('environment:changed', { python: true }); await resolver.pending;
  assert.equal(resolver.get('python-tool').applicability, 'UNVERIFIED');
  await resolver.review('python-tool', { eligible: true, evidence: 'Reviewed for isolated verification' });
  await resolver.verify('python-tool', { ok: true, digest: 'abc', checks: ['observed test'], at: 10 });
  await resolver.register({ id: 'dependent', source: 'donor', digest: 'def', dependencies: ['python-tool'] });
  await resolver.review('dependent', { eligible: true, evidence: 'isolated review' });
  await resolver.verify('dependent', { ok: true, digest: 'def', checks: ['observed test'] });
  assert.equal(resolver.get('dependent').applicability, 'ACTIVE');
  await resolver.updateEnvironment({ python: false });
  assert.equal(resolver.get('dependent').applicability, 'DEFERRED');
  await resolver.review('python-tool', { eligible: false, evidence: 'Rejected source' });
  await resolver.updateEnvironment({ python: true });
  assert.equal(resolver.get('python-tool').applicability, 'BLOCKED');
  assert.equal(resolver.get('dependent').applicability, 'DEFERRED');
  const restarted = resolverComputer(persistence); await restarted.state.restore(); await restarted.contextual.boot();
  assert.deepEqual(restarted.contextual.get('python-tool').source, { repository: 'original', version: 'v1' });
  assert.equal(restarted.contextual.get('python-tool').lastSuccessfulExecution, 10);
  await restarted.contextual.register({ id: 'python-tool', source: { repository: 'original', version: 'v1' }, digest: 'new', environment: ['python'] });
  assert.equal(restarted.contextual.get('python-tool').applicability, 'UNVERIFIED');
  assert.equal(restarted.contextual.get('python-tool').securityEligibility, 'UNVERIFIED');
  assert.ok(restarted.contextual.data().history.length >= 7);
});

test('guarded plans reject paths, approval forgery, duplicate keys and unauthorized execution; interrupted jobs never replay', async () => {
  const computer = await new ComputerRuntime().boot();
  const research = await new ProjectResearch(computer).boot();
  const imported = await research.import({ name: 'guard-test', files: [{ path: 'package.json', content: '{"scripts":{"build":"true","test":"true"}}' }] });
  const worker = await new ConstructionWorker(computer).boot();
  const spec = { projectId: imported.project.id, goal: 'Inspect guarded build', changes: [], requestKey: 'guard-test-key' };
  await assert.rejects(() => worker.propose({ ...spec, changes: [{ path: '../escape', content: 'bad' }] }));
  const job = await worker.propose(spec);
  assert.equal((await worker.propose(spec)).id, job.id);
  await assert.rejects(() => worker.propose({ ...spec, goal: 'Different goal' }));
  await assert.rejects(() => worker.run(job.id));
  await assert.rejects(() => worker.approve(job.id, { decision: 'approve', planDigest: 'forged' }));
  const planDigest = digest(JSON.stringify(job.spec));
  await worker.approve(job.id, { decision: 'deny', planDigest });
  await assert.rejects(() => worker.run(job.id));
  const data = worker.data(); data.jobs[job.id].status = 'RUNNING'; data.jobs[job.id].attempts = 1;
  await computer.state.set('computer.construction', data);
  const restarted = await new ConstructionWorker(computer).boot();
  assert.equal(restarted.data().jobs[job.id].status, 'INTERRUPTED');
  await assert.rejects(() => restarted.run(job.id));
  const unavailable = await new ConstructionWorker(computer, { runner: { available: async () => ({ available: false, reason: 'fixture unavailable environment' }) } }).boot();
  const second = await unavailable.propose({ ...spec, requestKey: 'unavailable-key' });
  await unavailable.approve(second.id, { decision: 'approve', planDigest: digest(JSON.stringify(second.spec)) });
  assert.equal((await unavailable.run(second.id)).attempts, 0);
  assert.equal(unavailable.data().jobs[second.id].status, 'APPROVED');
  research.close();
});

test('real unfinished application: import, defer, observe, repair, Docker build/tests, artifact and disk restart', { skip: process.env.SYNTHIA_DOCKER_TEST !== '1', timeout: 180000 }, async () => {
  const directory = await mkdtemp(join(tmpdir(), 'synthia-acceptance-'));
  let research;
  const proof = [];
  try {
    const boot = () => new ComputerRuntime({ persistence: new JsonFilePersistence(join(directory, 'state.json')), eventLogPath: join(directory, 'events.jsonl') }).boot();
    const computer = await boot();
    research = await new ProjectResearch(computer).boot();
    await computer.contextual.updateEnvironment({ 'runtime:node': true });
    const fixture = new URL('./fixtures/unfinished-budget/', import.meta.url);
    const paths = ['package.json', 'build.mjs', 'budget.test.mjs', 'src/budget.mjs'];
    const files = await Promise.all(paths.map(async path => ({ path, content: await readFile(new URL(path, fixture), 'utf8') })));
    const { project } = await research.import({ name: 'Unfinished budget application', source: 'acceptance-fixture/unfinished-budget', files });
    const capabilityId = `project:${project.id}`;
    const before = computer.contextual.get(capabilityId);
    assert.equal(before.applicability, 'DEFERRED');
    assert.equal(computer.queryCapability(capabilityId).contextual.applicability, 'DEFERRED');
    assert.equal(computer.route(capabilityId).selected_provider, null);
    assert.ok(before.reasons.some(reason => reason.includes('settings.mjs')));
    proof.push({ stage: 'genuine-missing-source', capability: before });
    const worker = await new ConstructionWorker(computer).boot();
    assert.equal((await worker.runner.available()).available, true, 'Docker image must be provisioned for real acceptance');
    const sentinel = join(directory, 'host-only-marker');
    await writeFile(sentinel, 'host boundary fixture');
    const conversation = new ConversationExecution(computer);
    const isolated = await conversation.executeArtifact({ name: 'isolation-check.js', type: 'javascript',
      content: `const fs = await import('node:fs'); console.log(fs.existsSync(${JSON.stringify(sentinel)}));` });
    assert.equal(isolated.ok, true);
    assert.deepEqual(isolated.result.result.stdout, ['false'], 'Legacy Run path cannot read a host-only file');
    proof.push({ stage: 'legacy-execution-isolated', receipt: isolated });
    const submit = async (goal, changes, key) => {
      const job = await worker.propose({ projectId: project.id, goal, changes, requestKey: key });
      await worker.approve(job.id, { decision: 'approve', planDigest: digest(JSON.stringify(job.spec)) });
      return computer.processes.execute('bounded-construction', { id: job.id });
    };
    const missing = await submit('Verify genuine missing dependency failure', [], 'missing-dependency-build');
    assert.equal(missing.status, 'FAILED_VERIFICATION');
    assert.equal(computer.contextual.get(`build:${missing.id}`).applicability, 'FAILED_VERIFICATION');
    assert.match(missing.receipt.stderr, /ERR_MODULE_NOT_FOUND/);
    proof.push(missing);
    // Explicit fixture authorization: introduce the actual missing file through resident workspace.
    await computer.projects.writeFile(project.id, 'src/settings.mjs', "export const currency = '$';\n");
    await research.pending;
    const reactivated = computer.contextual.get(capabilityId);
    assert.equal(reactivated.id, before.id); assert.deepEqual(reactivated.source, before.source);
    assert.equal(reactivated.applicability, 'UNVERIFIED');
    assert.ok(research.search('Sum all transactions').length);
    const broken = await submit('Observe genuine failing application test after dependency restoration', [], 'failing-build-test');
    assert.equal(broken.status, 'FAILED_VERIFICATION'); assert.match(broken.receipt.stdout, /not ok/);
    proof.push(broken);
    const repairedSource = "import { currency } from './settings.mjs';\nexport function balance(entries) { return `${currency}${entries.reduce((sum, value) => sum + value, 0).toFixed(2)}`; }\n";
    const completed = await submit('Repair evidenced sum defect in isolated copy', [{ path: 'src/budget.mjs', content: repairedSource }], 'approved-budget-repair');
    assert.equal(completed.status, 'VERIFIED', JSON.stringify(completed.receipt));
    assert.match(completed.receipt.stdout, /Built budget module into dist/);
    assert.match(completed.receipt.stdout, /pass 1/);
    assert.equal(computer.projects.readFile(project.id, 'src/budget.mjs').content, files.find(file => file.path === 'src/budget.mjs').content);
    await assert.rejects(() => worker.run(completed.id));
    const artifact = worker.artifact(completed.id);
    assert.ok(computer.artifacts.get(worker.data().artifacts[completed.id].artifactId), 'Deliverable is admitted through the existing artifact registry');
    assert.equal(artifact.files.find(file => file.path === 'src/budget.mjs').content, repairedSource);
    assert.equal(computer.capabilities.resolve(`build:${completed.id}`).available, true);
    proof.push(completed, artifact);
    research.close();
    const restarted = await boot();
    const restoredResearch = await new ProjectResearch(restarted).boot();
    const restoredWorker = await new ConstructionWorker(restarted).boot();
    assert.deepEqual(restoredWorker.data().jobs[completed.id].receipt, completed.receipt);
    assert.deepEqual(restoredWorker.artifact(completed.id), artifact);
    assert.equal(restoredWorker.data().approvals.length, 3);
    assert.equal(restoredResearch.snapshot().reports[0].digest, reactivated.digest);
    assert.equal(restarted.state.get(`computer.research.originals.${project.id}`).files.length, 4);
    assert.equal(Object.keys(restarted.state.get(`computer.research.revisions.${project.id}`)).length, 2);
    assert.equal(restoredWorker.data().jobs[completed.id].attempts, 1);
    assert.ok(restarted.contextual.data().history.some(event => event.id === capabilityId && event.to === 'DEFERRED'));
    proof.push({ stage: 'disk-restart-confirmed', projectId: project.id, receiptId: completed.receipt.id, cursor: restoredResearch.snapshot().cursors });
    restoredResearch.close();
    if (process.env.SYNTHIA_PROOF_PATH) await writeFile(process.env.SYNTHIA_PROOF_PATH, JSON.stringify(proof, null, 2));
  } finally { research?.close(); await rm(directory, { recursive: true, force: true }); }
});
